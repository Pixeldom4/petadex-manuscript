#!/usr/bin/env python3
"""Build petadex-figure-3-composite.svg from the three Figure 3 panels.

Panels are inlined (self-contained, like the Figure 1 composite) at native scale,
1 user unit = 1 mm, so their matplotlib text stays the same size in every panel:

    a  ../3a_coverage.svg   b  ../3b_map.svg      (top row)
    c  ../3c_profiles.svg                          (bottom row, left-aligned)

matplotlib reuses the same element ids in every file (figure_1, axes_1, ...), so
each panel's ids are prefixed (p3a-, p3b-, p3c-) to keep the composite valid.
The panels carry their own a/b/c titles, so the composite adds none.

Usage:  python3 figure-svgs/figure-composites/build-figure-3-composite.py
"""
import re
from pathlib import Path

HERE = Path(__file__).resolve().parent
PANELS = HERE.parent
OUT = HERE / "petadex-figure-3-composite.svg"
PT = 25.4 / 72          # 1 pt in mm
MARGIN, GAP = 5.0, 6.0  # mm
BACKGROUND = "#fcfcfb"  # the panels' own figure background


def load(name, prefix):
    text = (PANELS / name).read_text()
    root = re.search(r"<svg\b[^>]*>", text).group(0)
    w = float(re.search(r'\bwidth="([\d.]+)pt"', root).group(1))
    h = float(re.search(r'\bheight="([\d.]+)pt"', root).group(1))
    vb = re.search(r'viewBox="([^"]+)"', root).group(1)
    body = text[text.index(root) + len(root): text.rindex("</svg>")]
    body = re.sub(r"<metadata>.*?</metadata>", "", body, flags=re.S)
    body = re.sub(r'\bid="([^"]+)"', rf'id="{prefix}\1"', body)
    body = re.sub(r"url\(#([^)]+)\)", rf"url(#{prefix}\1)", body)
    body = re.sub(r'href="#([^"]+)"', rf'href="#{prefix}\1"', body)
    return dict(w=w * PT, h=h * PT, vb=vb, body=body, prefix=prefix, name=name)


def main():
    a = load("3a_coverage.svg", "p3a-")
    b = load("3b_map.svg", "p3b-")
    c = load("3c_profiles.svg", "p3c-")
    a["x"], a["y"] = MARGIN, MARGIN
    b["x"], b["y"] = MARGIN + a["w"] + GAP, MARGIN
    c["x"], c["y"] = MARGIN, MARGIN + max(a["h"], b["h"]) + GAP
    W = max(b["x"] + b["w"], c["x"] + c["w"]) + MARGIN
    H = c["y"] + c["h"] + MARGIN
    px = round(160 / 25.4 * 600)  # 600 DPI at the 160 mm text width
    parts = [
        '<?xml version="1.0" encoding="UTF-8" standalone="no"?>',
        "<!-- Figure 3 composite (metadata). Generated by build-figure-3-composite.py from",
        "     ../3a_coverage.svg, ../3b_map.svg and ../3c_profiles.svg; edit the panels and re-run,",
        "     not this file. Panels inlined at native scale (1 user unit = 1 mm).",
        f"     Export: 600 DPI at the 160 mm text width = export width {px} px. -->",
        f'<svg width="{W:.3f}mm" height="{H:.3f}mm" viewBox="0 0 {W:.3f} {H:.3f}" version="1.1"'
        ' id="figure-3-composite"',
        '   inkscape:export-filename="../../figures/f3.metadata.png"',
        '   xmlns="http://www.w3.org/2000/svg" xmlns:xlink="http://www.w3.org/1999/xlink"',
        '   xmlns:inkscape="http://www.inkscape.org/namespaces/inkscape">',
        f'<rect id="composite-background" x="0" y="0" width="{W:.3f}" height="{H:.3f}" fill="{BACKGROUND}"/>',
    ]
    for p, label in ((a, "a"), (b, "b"), (c, "c")):
        parts.append(f'<g id="panel-3{label}-group" inkscape:groupmode="layer" inkscape:label="3{label} ({p["name"]})">')
        parts.append(f'<svg id="panel-3{label}" x="{p["x"]:.3f}" y="{p["y"]:.3f}" width="{p["w"]:.3f}" '
                     f'height="{p["h"]:.3f}" viewBox="{p["vb"]}">')
        parts.append(p["body"].strip())
        parts.append("</svg>\n</g>")
    parts.append("</svg>\n")
    OUT.write_text("\n".join(parts))
    print(f"wrote {OUT.name}: {W:.1f} x {H:.1f} mm")


if __name__ == "__main__":
    main()
